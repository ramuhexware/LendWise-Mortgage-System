-- Sequences
CREATE SEQUENCE SEQ_CREDIT_RESPONSE_ID START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_CREDIT_ID START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_TRADELINE_ID START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_DECISION_ID START WITH 1 INCREMENT BY 1;
