-- LendWise Mortgage System - Pricing Tables
-- Oracle Database Schema - Flow 5: Product Pricing Engine & Rate Lock
-- ============================================================================

-- Loan products reference table
CREATE TABLE LOAN_PRODUCTS (
    PRODUCT_ID          VARCHAR2(20) PRIMARY KEY,
    PRODUCT_NAME        VARCHAR2(100) NOT NULL,
    PRODUCT_TYPE        VARCHAR2(30) NOT NULL,  -- CONVENTIONAL, FHA, VA, USDA, JUMBO
    TERM_MONTHS         NUMBER(3) NOT NULL,  -- 180, 240, 360
    RATE_TYPE           VARCHAR2(10) NOT NULL,  -- FIXED, ARM
    ARM_INDEX           VARCHAR2(30),  -- SOFR, LIBOR
    ARM_MARGIN          NUMBER(6,4),
    ARM_CAPS            VARCHAR2(30),  -- 2/2/5, 5/2/5
    MIN_LOAN_AMOUNT     NUMBER(12,2),
    MAX_LOAN_AMOUNT     NUMBER(12,2),
    MIN_LTV             NUMBER(5,2),
    MAX_LTV             NUMBER(5,2),
    MIN_FICO            NUMBER(3),
    MAX_DTI             NUMBER(5,2),
    OCCUPANCY_TYPES     VARCHAR2(100),  -- PRIMARY,SECONDARY,INVESTMENT
    PROPERTY_TYPES      VARCHAR2(200),  -- SINGLE_FAMILY,CONDO,TOWNHOUSE
    IS_ACTIVE           CHAR(1) DEFAULT 'Y',
    EFFECTIVE_DATE      DATE,
    EXPIRATION_DATE     DATE
);

-- Base interest rates
CREATE TABLE BASE_RATES (
    RATE_ID             NUMBER PRIMARY KEY,
    PRODUCT_ID          VARCHAR2(20) NOT NULL,
    EFFECTIVE_DATE      DATE NOT NULL,
    EXPIRATION_DATE     DATE,
    BASE_RATE           NUMBER(6,4) NOT NULL,
    PAR_PRICE           NUMBER(8,4) DEFAULT 100.0000,
    LOCK_PERIOD_DAYS    NUMBER(3),
    CREATED_DATE        TIMESTAMP DEFAULT SYSTIMESTAMP,
    CREATED_BY          VARCHAR2(100),
    CONSTRAINT FK_RATE_PRODUCT FOREIGN KEY (PRODUCT_ID)
        REFERENCES LOAN_PRODUCTS(PRODUCT_ID)
);

-- Loan Level Price Adjustments (LLPA)
CREATE TABLE LLPA_ADJUSTMENTS (
    LLPA_ID             NUMBER PRIMARY KEY,
    ADJUSTMENT_NAME     VARCHAR2(100) NOT NULL,
    ADJUSTMENT_TYPE     VARCHAR2(30) NOT NULL,  -- LTV, FICO, PROPERTY_TYPE, OCCUPANCY, STATE
    CRITERIA_MIN        NUMBER(10,4),
    CRITERIA_MAX        NUMBER(10,4),
    CRITERIA_VALUE      VARCHAR2(50),
    ADJUSTMENT_RATE     NUMBER(6,4) NOT NULL,  -- Basis points (negative = discount)
    ADJUSTMENT_PRICE    NUMBER(8,4),  -- Price adjustment
    PRODUCT_TYPES       VARCHAR2(200),  -- Comma-separated product types
    EFFECTIVE_DATE      DATE NOT NULL,
    EXPIRATION_DATE     DATE,
    IS_ACTIVE           CHAR(1) DEFAULT 'Y',
    NOTES               VARCHAR2(500)
);

