-- Compliance rule definitions
CREATE TABLE COMPLIANCE_RULES (
    RULE_ID             VARCHAR2(20) PRIMARY KEY,
    RULE_NAME           VARCHAR2(100) NOT NULL,
    RULE_CATEGORY       VARCHAR2(50) NOT NULL,  -- TRID, QM_ATR, HMDA, ECOA, RESPA
    RULE_TYPE           VARCHAR2(30),  -- TIMING, FEE_TOLERANCE, DTI_LIMIT, DISCLOSURE
    DESCRIPTION         VARCHAR2(1000),
    THRESHOLD_VALUE     NUMBER(10,4),
    THRESHOLD_TYPE      VARCHAR2(20),  -- PERCENT, DAYS, AMOUNT
    SEVERITY_IF_FAILED  VARCHAR2(20),  -- FATAL, MODERATE, LOW
    REGULATION_CITE     VARCHAR2(100),
    EFFECTIVE_DATE      DATE,
    EXPIRATION_DATE     DATE,
    IS_ACTIVE           CHAR(1) DEFAULT 'Y'
);

