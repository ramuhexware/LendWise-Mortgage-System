-- Indexes
CREATE INDEX IDX_CREDIT_RESP_LOAN ON CREDIT_BUREAU_RESPONSES(LOAN_ID);
CREATE INDEX IDX_CREDIT_HIST_LOAN ON CREDIT_HISTORY(LOAN_ID);
CREATE INDEX IDX_CREDIT_HIST_BORROWER ON CREDIT_HISTORY(BORROWER_ID);
CREATE INDEX IDX_TRADE_CREDIT ON CREDIT_TRADELINES(CREDIT_ID);
